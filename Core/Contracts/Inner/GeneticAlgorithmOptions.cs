namespace Core.Contracts.Inner;

/// <summary>
/// Настройки прогона, не относящиеся к предметной области: как гонять движок,
/// а не что оптимизировать. Отделены от задачи, чтобы одну и ту же задачу
/// можно было прогнать с разной интенсивностью операторов.
/// <para>
/// Inner-контракт: тип предоставляется вызывающему коду, реализовывать
/// его не нужно — достаточно инициализаторов свойств.
/// </para>
/// </summary>
public sealed record GeneticAlgorithmOptions
{
    /// <summary>
    /// Вероятность скрещивания пары родителей: <c>0…1</c>. По умолчанию <c>0.9</c>.
    /// Движок сам разыгрывает случайность — пользователь только задаёт порог.
    /// Если кроссовер не выполняется, оба родителя переходят в следующее
    /// поколение без изменений (кроме возможной мутации).
    /// </summary>
    public double CrossoverProbability { get; init; } = 0.9;

    /// <summary>
    /// Вероятность <b>вызова оператора мутации</b> для потомка: <c>0…1</c>,
    /// а не вероятность мутации отдельного гена. По умолчанию <c>0.1</c>.
    /// Классическая пер-генная вероятность (<c>0.01…0.1</c>) разыгрывается
    /// внутри реализации <see cref="Core.Contracts.Outer.IMutation{TChromosome}"/> —
    /// иначе движок и оператор перемножили бы два независимых порога,
    /// и итоговая частота оказалась бы меньше ожидаемой.
    /// <para>
    /// При <c>0</c> мутации не происходит вовсе, при <c>1</c> — оператор
    /// вызывается для каждого потомка.
    /// </para>
    /// </summary>
    public double MutationProbability { get; init; } = 0.1;
}
