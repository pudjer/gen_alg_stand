namespace Core.Contracts.Outer;

/// <summary>
/// Целевая функция задачи. Всегда минимизируется: меньше — лучше.
/// <para>
/// Задачам максимизации не нужен отдельный флаг — реализация возвращает
/// отрицание своей целевой функции: <c>-value</c> вместо <c>value</c>.
/// Благодаря этому движку и всем стратегиям известно единственное
/// направление сравнения, и вопроса «а больше — это лучше?» не возникает
/// ни в одной точке API.
/// </para>
/// </summary>
/// <typeparam name="TChromosome">Конкретный тип хромосомы задачи.</typeparam>
public interface ILossFunction<TChromosome>
    where TChromosome : IChromosome
{
    /// <summary>
    /// Значение потерь хромосомы — чистая функция от хромосомы.
    /// Данные прогона движок не передаёт: если функции нужны поколение,
    /// популяция или случайность, реализация сама доставляет их через
    /// собственные зависимости (конструктор).
    /// </summary>
    double Evaluate(TChromosome chromosome);
}
