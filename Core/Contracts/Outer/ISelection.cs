using Core.Contracts.Inner;

namespace Core.Contracts.Outer;

/// <summary>
/// Стратегия отбора родителей.
/// </summary>
/// <typeparam name="TChromosome">Конкретный тип хромосомы задачи.</typeparam>
public interface ISelection<TChromosome>
    where TChromosome : IChromosome
{
    /// <summary>
    /// Возвращает родителей для следующего поколения. Сколько их будет —
    /// решает сама стратегия: движок не знает размера популяции.
    /// Всё, что нужно для решения, передаётся аргументами: текущая
    /// популяция с потерями и случайность. Меньшие потери лучше —
    /// направление сравнения задано самой сигнатурой, флага направления нет.
    /// <para>
    /// <b>Порядок значим.</b> Движок скрещивает соседние пары:
    /// <c>(0,1)</c>, <c>(2,3)</c>, … . Список, отсортированный по потерям,
    /// даст скрещивание лучших между собой; если нужны случайные пары,
    /// перемешайте список сами — случайность для этого передаётся.
    /// </para>
    /// <para>
    /// <b>Число родителей задаёт размер следующего поколения</b>: элита занимает
    /// один слот, остальные заполняются потомками. Возвращайте минимум двух —
    /// на одном родителе эволюция вырождается в цепочку мутаций.
    /// </para>
    /// </summary>
    IReadOnlyList<TChromosome> Select(
        IPopulation<TChromosome> population,
        IRandom random);
}
